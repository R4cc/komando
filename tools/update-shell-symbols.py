"""Refresh the pinned Tabler shell symbols and Simple Icons distro marks."""
import concurrent.futures
import json
import re
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
TABLER = "4581ad20d8d13e24f6c3be75caaea1c4ad6c4b35"
SIMPLE = "74fa843c81f86d7fe28fe54b6f206efb3104af13"
# Theme-aware accent pairs, chosen for the compact sidebar rather than brand-guide colors.
DISTROS = {
    "ubuntu": (0xf38c58, 0xb74716), "debian": (0xfb7699, 0xb62150),
    "kalilinux": (0x8fb5e9, 0x225a99), "opensuse": (0x8dd77b, 0x30712c),
    "fedora": (0x82b4ef, 0x2a5f9e), "almalinux": (0xe5bd65, 0x826515),
    "rockylinux": (0x75d7b2, 0x19775a), "centos": (0xc2a5ed, 0x76519d),
    "redhat": (0xf48181, 0xb83232), "archlinux": (0x71c0e5, 0x1d6d94),
    "gentoo": (0xb9a8e5, 0x72569d), "nixos": (0x91c0ea, 0x366e9c),
    "linuxmint": (0xa8ce79, 0x4d7024), "linux": (None, None),
}

def fetch(url):
    with urllib.request.urlopen(url, timeout=30) as response:
        return response.read()

def main():
    dest = ROOT / "assets/shell-symbols"
    dest.mkdir(parents=True, exist_ok=True)
    simple_base = f"https://raw.githubusercontent.com/simple-icons/simple-icons/{SIMPLE}/"
    tabler_base = f"https://raw.githubusercontent.com/tabler/tabler-icons/{TABLER}/"
    metadata = json.loads(fetch(simple_base + "data/simple-icons.json"))
    by_name = {re.sub(r'[^a-z0-9]', '', item['title'].lower()): item for item in metadata}
    entries = []
    jobs = [("tabler", "brand-powershell", tabler_base + "icons/outline/brand-powershell.svg", (0x72adff, 0x2366b5), "tabler outline powershell pwsh windows-powershell"),
            ("tabler", "terminal-2", tabler_base + "icons/outline/terminal-2.svg", (None, None), "tabler outline terminal console command-prompt cmd windows")]
    for name, colors in DISTROS.items():
        item = by_name[name]
        aliases = " ".join([item['title'], name, "simple-icons simpleicons"])
        jobs.append(("simpleicons", name, simple_base + f"icons/{name}.svg", colors, aliases))
    def download(job):
        family, name, url, colors, search = job
        folder = dest / family
        folder.mkdir(exist_ok=True)
        svg = fetch(url)
        assert b"<svg" in svg
        (folder / (name + ".svg")).write_bytes(svg)
        color = lambda value: "None" if value is None else f"Some(0x{value:06x})"
        return f'    SymbolIcon {{ id: "{family}:{name}", search: {json.dumps(search)}, svg: include_bytes!("../../assets/shell-symbols/{family}/{name}.svg"), color_dark: {color(colors[0])}, color_light: {color(colors[1])} }},'
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as pool:
        entries = sorted(pool.map(download, jobs))
    (ROOT / "src/icons/symbols.rs").write_text('// Generated by tools/update-shell-symbols.py.\nuse super::SymbolIcon;\n' + f'pub static SYMBOLS: [SymbolIcon; {len(entries)}] = [\n' + '\n'.join(entries) + '\n];\n', encoding="utf-8", newline="\n")
    (dest / "LICENSE-tabler").write_bytes(fetch(tabler_base + "LICENSE"))
    (dest / "LICENSE-simple-icons.md").write_bytes(fetch(simple_base + "LICENSE.md"))
    (dest / "DISCLAIMER-simple-icons.md").write_bytes(fetch(simple_base + "DISCLAIMER.md"))
    (dest / "simple-icons-metadata.json").write_text(json.dumps([by_name[name] for name in DISTROS], indent=2) + "\n", encoding="utf-8")
    print(f"Bundled {len(jobs)} shell and distro symbols")

if __name__ == "__main__":
    main()
